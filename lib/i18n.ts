export function createTranslator(language: Language) {
  return (text: string, values: Record<string, string | number> = {}) => {
    const translated = language === 'ru' ? (russian[text] ?? text) : text;
    return translated.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
  };
}

export function createFormatters(language: Language) {
  const locale = language === 'ru' ? 'ru-RU' : 'en-US';
  return {
    compact: (n: number) => new Intl.NumberFormat(locale, { notation: 'compact', maximumFractionDigits: 2 }).format(n),
    num: (n: number) => new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).format(n),
    decimal: (n: number) => new Intl.NumberFormat(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(n),
    pct: (n: number) => new Intl.NumberFormat(locale, { style: 'percent', minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(n),
  };
}

export function readPreferences(storage: Pick<Storage, 'getItem'>, prefersDark = false): { language: Language; theme: Theme } {
  let language: Language = 'en';
  let theme: Theme = prefersDark ? 'dark' : 'light';
  try {
    const savedLanguage = storage.getItem('sr-language');
    const savedTheme = storage.getItem('sr-theme');
    if (savedLanguage === 'en' || savedLanguage === 'ru') language = savedLanguage;
    if (savedTheme === 'light' || savedTheme === 'dark') theme = savedTheme;
  } catch { /* Preferences are optional when browser storage is blocked. */ }
  return { language, theme };
}
